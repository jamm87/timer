const LANG_KEY = 'fichaje.lang';

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {}
  for (const l of navigator.languages || [navigator.language || '']) {
    const code = l.slice(0, 2).toLowerCase();
    if (STRINGS[code]) return code;
  }
  return 'es';
}

let lang = detectLang();

function t(key, params = {}) {
  const str = STRINGS[lang][key] ?? STRINGS.es[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, p) => (p in params ? params[p] : `{${p}}`));
}

function locale() {
  return LANGS[lang].locale;
}

function setLang(code) {
  if (!STRINGS[code]) return;
  lang = code;
  try {
    localStorage.setItem(LANG_KEY, code);
  } catch {}
  applyTranslations();
}

// Traduce los elementos estáticos marcados con data-i18n / -title / -placeholder / -aria
function applyTranslations() {
  document.documentElement.lang = lang;
  document.documentElement.dir = LANGS[lang].dir;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}
